# 다른 게임 언어용 문구 복사본 생성기(2026-10-26).
# Stellaris 는 지금 게임 언어의 문구가 없으면 영어로 대신 보여 주지 않고 키 이름(예: sllm_khan_favor)을 그대로 띄운다.
# 그래서 모드가 직접 번역하지 않는 언어(한국어 말고 전부)마다 영어 문구 전체를 파일 하나로 합쳐 둔다. 한국어 폴더는 건드리지 않는다.
# 규칙(src/loc-fallback-check.ts 의 locFallbackFile 과 같아야 한다 — 자체 검사가 비교함):
#   localisation/english/*_l_english.yml(이름순) → localisation/<언어>/sllm_fallback_l_<언어>.yml
#   BOM + l_<언어>: + 안내 주석, 그다음 파일마다 「# <파일 이름>」 줄과 l_english: 다음 줄들. 줄바꿈은 LF.
# 영어 문구를 고친 뒤에는 다시 돌린다. 실행: python tools/gen-loc-fallback.py <tester-mod 폴더>
import os, sys

LANGS = ['braz_por', 'french', 'german', 'japanese', 'polish', 'russian', 'simp_chinese', 'spanish']
NOTE = '# Auto-generated from the English files by tools/gen-loc-fallback.py. Edit the English files and re-run; do not edit this file.'

def body(en):
    t = en.lstrip('\ufeff').replace('\r\n', '\n')
    i = t.index('l_english:') + len('l_english:')
    return t[i:].lstrip('\n').rstrip('\n')

def fallback_text(files, lang):
    out = ['\ufeffl_' + lang + ':', NOTE]
    for name, en in files:
        out.append('# ' + name)
        b = body(en)
        if b:
            out.append(b)
    return '\n'.join(out) + '\n'

def main(mod):
    src = os.path.join(mod, 'localisation', 'english')
    files = []
    for f in sorted(os.listdir(src)):
        if f.endswith('_l_english.yml'):
            with open(os.path.join(src, f), 'r', encoding='utf-8', newline='') as h:
                files.append((f, h.read()))
    for lang in LANGS:
        d = os.path.join(mod, 'localisation', lang)
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, 'sllm_fallback_l_' + lang + '.yml'), 'w', encoding='utf-8', newline='') as h:
            h.write(fallback_text(files, lang))
    print(f'{len(files)} english files -> {len(LANGS)} languages')

if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), '..', 'tester-mod'))
