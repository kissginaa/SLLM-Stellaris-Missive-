// 다른 게임 언어용 문구 복사본 검사(2026-10-26). selftest.ts 에서 runLocFallbackChecks() 로 부른다.
// Stellaris 는 게임 언어의 문구가 없으면 영어로 대신 보여 주지 않고 키 이름을 띄운다 → 모드가 번역하지 않는 언어마다 영어 문구 전체를 파일 하나로 합쳐 둔다.
// 파일은 tools/gen-loc-fallback.py 가 만든다. 이 검사는 영어 문구를 고치고 다시 만들지 않은 경우를 잡는다.
import * as fs from 'fs';
import * as path from 'path';

export const LOC_FALLBACK_LANGS = ['braz_por', 'french', 'german', 'japanese', 'polish', 'russian', 'simp_chinese', 'spanish'] as const;
const NOTE = '# Auto-generated from the English files by tools/gen-loc-fallback.py. Edit the English files and re-run; do not edit this file.';

const body = (en: string): string => {
  const t = en.replace(/^\ufeff+/, '').replace(/\r\n/g, '\n'), i = t.indexOf('l_english:');
  if (i < 0) throw new Error('NO_L_ENGLISH');
  return t.slice(i + 'l_english:'.length).replace(/^\n+/, '').replace(/\n+$/, '');
};
/** 영어 파일들(이름순 [이름, 내용]) → 그 언어 합본(gen-loc-fallback.py 의 fallback_text 와 같은 규칙). */
export function locFallbackFile(files: Array<[string, string]>, lang: string): string {
  const out = ['\ufeffl_' + lang + ':', NOTE];
  for (const [name, en] of files) { out.push('# ' + name); const b = body(en); if (b) out.push(b); }
  return out.join('\n') + '\n';
}

export function runLocFallbackChecks(): void {
  const check = (ok: boolean, name: string) => { console.log((ok ? 'PASS ' : 'FAIL ') + 'loc-fallback: ' + name); if (!ok) process.exitCode = 1; };
  // 규칙
  const got = locFallbackFile([['a_l_english.yml', '\ufeffl_english:\r\n a:0 "A"\r\n'], ['b_l_english.yml', 'l_english:\n b:0 "B"\n\n']], 'french');
  check(got === '\ufeffl_french:\n' + NOTE + '\n# a_l_english.yml\n a:0 "A"\n# b_l_english.yml\n b:0 "B"\n', 'merge keeps keys, one header, BOM, LF');
  check(!LOC_FALLBACK_LANGS.includes('korean' as never) && !LOC_FALLBACK_LANGS.includes('english' as never), 'korean and english are not overwritten');
  // 모드 폴더: 언어마다 합본이 있고 지금 영어 문구와 같다.
  const md = process.env.SLLM_MRD_MOD || path.join(__dirname, '..', 'tester-mod'), enDir = path.join(md, 'localisation', 'english');
  let files: Array<[string, string]> = [];
  try { files = fs.readdirSync(enDir).filter((f) => f.endsWith('_l_english.yml')).sort().map((f) => [f, fs.readFileSync(path.join(enDir, f), 'utf8')] as [string, string]); } catch { /* 모드 폴더 없음 */ }
  check(files.length > 0, 'english files found');
  const stale = LOC_FALLBACK_LANGS.filter((lang) => {
    let t = ''; try { t = fs.readFileSync(path.join(md, 'localisation', lang, `sllm_fallback_l_${lang}.yml`), 'utf8'); } catch { /* 없음 */ }
    return t !== locFallbackFile(files, lang);
  });
  check(stale.length === 0, 'fallback files up to date (run tools/gen-loc-fallback.py)' + (stale.length ? ': ' + stale.join(', ') : ''));
  // 키 수: 영어 전체 = 합본
  const keys = (s: string) => (s.match(/^\s+[A-Za-z0-9_.\-]+:\d*\s*"/gm) ?? []).length;
  const enKeys = files.reduce((n, [, t]) => n + keys(t), 0);
  let fr = ''; try { fr = fs.readFileSync(path.join(md, 'localisation', 'french', 'sllm_fallback_l_french.yml'), 'utf8'); } catch { /* 없음 */ }
  check(enKeys > 0 && keys(fr) === enKeys, `fallback has every English key (${enKeys})`);
}
